def open_file(path: str, text: str | None = None) -> str:
    return f'<walkthrough-editor-open-file filePath="{path}">{text or path}</walkthrough-editor-open-file>'


def code(lang: str, body: str) -> str:
    return f"```{lang}\n{body.rstrip()}\n```\n"


def paste_step(checkpoint: str) -> str:
    """The whole checkpoint file, then: open my_agent, select all, paste, save.

    Copy comes first: the copy button takes the focus away from the editor, and the open link gives it back.
    """
    body = (ROOT / "agents" / checkpoint / "agent.py").read_text(encoding="utf-8")
    return f"""### Paste the new version

**Copy the code.** Click the copy button at the top right of the code below. It's the whole
file, with the new parts explained in its comments.

{code("python", body)}
**Paste and save.** Click {open_file(MY_AGENT)} to open it. Press Ctrl+A (⌘A on a Mac) to
select everything, Ctrl+V (⌘V) to paste over it, then Ctrl+S (⌘S) to save.

The same file is in {open_file(f"agents/{checkpoint}/agent.py")}. If you'd rather read than
paste, select `{checkpoint}` in the dev UI instead of `my_agent`.
"""


RUNNING = f"""### Run it

The dev UI from step 1 keeps running in the first terminal tab, and it loads your file again when
you save. If it stopped, run this again in the first tab:

{code("bash", ADK_WEB)}"""


